// GenerateMixedScript generates a sysbench Lua script for mixed workloads.
// threads is used to partition pre-generated UUIDs across sysbench threads.
// Uses a lookup table (tableName_ids) for random key selection in read/update operations.
func GenerateMixedScript(keyType, tableName string, insertWeight, readWeight, updateWeight, threads int) string {
	if insertWeight+readWeight+updateWeight != 100 {
		return fmt.Sprintf(`-- Error: Weights must sum to 100 (got %d)`, insertWeight+readWeight+updateWeight)
	}

	insertThreshold := insertWeight
	readThreshold := insertWeight + readWeight
	lookupTable := tableName + "_ids"

	insertScript := generateMixedInsertSQL(keyType, tableName)

	switch keyType {
	case "sequential":
		return fmt.Sprintf(`
-- Sysbench MIXED script for BIGINT AUTO_INCREMENT
-- Weights: INSERT=%d%%, READ=%d%%, UPDATE=%d%%
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
	num_records = {"Number of records", 0},
}

local insert_threshold = %d
local read_threshold = %d

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()
end

function thread_done()
	con:disconnect()
end

function event()
	local op = sysbench.rand.uniform(1, 100)

	if op <= insert_threshold then
		%s
	elseif op <= read_threshold then
		local rn = sysbench.rand.uniform(1, math.max(1, sysbench.opt.num_records))
		con:query("SELECT * FROM %s WHERE id = (SELECT id FROM %s WHERE rn = " .. rn .. ")")
	else
		local rn = sysbench.rand.uniform(1, math.max(1, sysbench.opt.num_records))
		con:query("UPDATE %s SET data = UNHEX(REPEAT('42', 1024)) WHERE id = (SELECT id FROM %s WHERE rn = " .. rn .. ")")
	end
end
`, insertWeight, readWeight, updateWeight, tableName, insertThreshold, readThreshold,
			insertScript, tableName, lookupTable, tableName, lookupTable)

	case "uuidv4", "uuidv7", "uuidv1", "ulid", "ulid_monotonic":
		return fmt.Sprintf(`
-- Sysbench MIXED script for UUID/ULID types
-- Weights: INSERT=%d%%, READ=%d%%, UPDATE=%d%%
-- UUIDs pre-generated by Go libraries for proper time-ordering
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
	num_records = {"Number of records", 0},
}

local insert_threshold = %d
local read_threshold = %d

local uuids = {}
local uuid_idx = 0
local num_threads = %d

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()

	local f = io.open("/tmp/uuids.txt", "r")
	if f then
		for line in f:lines() do
			uuids[#uuids + 1] = line
		end
		f:close()
	end

	if #uuids > 0 then
		local per_thread = math.floor(#uuids / num_threads)
		uuid_idx = sysbench.tid * per_thread
	end
end

function thread_done()
	con:disconnect()
end

function event()
	local op = sysbench.rand.uniform(1, 100)

	if op <= insert_threshold then
		-- INSERT with pre-generated UUID
		uuid_idx = uuid_idx + 1
		local uuid_hex = uuids[uuid_idx]
		con:query("INSERT INTO %s (id, data) VALUES (UNHEX('" .. uuid_hex .. "'), UNHEX(REPEAT('41', 1024)))")
	elseif op <= read_threshold then
		local rn = sysbench.rand.uniform(1, math.max(1, sysbench.opt.num_records))
		con:query("SELECT * FROM %s WHERE id = (SELECT id FROM %s WHERE rn = " .. rn .. ")")
	else
		local rn = sysbench.rand.uniform(1, math.max(1, sysbench.opt.num_records))
		con:query("UPDATE %s SET data = UNHEX(REPEAT('42', 1024)) WHERE id = (SELECT id FROM %s WHERE rn = " .. rn .. ")")
	end
end
`, insertWeight, readWeight, updateWeight, tableName, insertThreshold, readThreshold, threads,
			tableName, tableName, lookupTable, tableName, lookupTable)

	default:
		return fmt.Sprintf(`-- Unknown key type: %s`, keyType)
	}
}

// generateMixedInsertSQL returns the Lua insert statement for sequential types in mixed workloads.
func generateMixedInsertSQL(keyType, tableName string) string {
	if keyType == "sequential" {
		return fmt.Sprintf(`con:query("INSERT INTO %s (data) VALUES (UNHEX(REPEAT('41', 1024)))")`, tableName)
	}
	return "" // UUID inserts handled in the UUID branch with pre-generated UUIDs
}

// GenerateBatchInsertScript generates a script for batch inserts.
// threads is used to partition pre-generated UUIDs across sysbench threads.
func GenerateBatchInsertScript(keyType, tableName string, batchSize, threads int) string {
	if batchSize <= 1 {
		return GenerateInsertScript(keyType, tableName, threads)
	}

	switch keyType {
	case "sequential":
		// Build VALUES clause for batch insert
		return fmt.Sprintf(`
-- Sysbench BATCH INSERT script for BIGINT AUTO_INCREMENT (batch size: %d)
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
}

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()
end

function thread_done()
	con:disconnect()
end

function event()
	local values = {}
	for i = 1, %d do
		table.insert(values, "(UNHEX(REPEAT('41', 1024)))")
	end
	con:query("INSERT INTO " .. sysbench.opt.table_name .. " (data) VALUES " .. table.concat(values, ","))
end
`, batchSize, tableName, batchSize)

	case "uuidv4", "uuidv7", "uuidv1", "ulid", "ulid_monotonic":
		return fmt.Sprintf(`
-- Sysbench BATCH INSERT script for UUID/ULID types (batch size: %d)
-- UUIDs pre-generated by Go libraries for proper time-ordering
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
}

local uuids = {}
local uuid_idx = 0
local num_threads = %d

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()

	local f = io.open("/tmp/uuids.txt", "r")
	if f then
		for line in f:lines() do
			uuids[#uuids + 1] = line
		end
		f:close()
	end

	local per_thread = math.floor(#uuids / num_threads)
	uuid_idx = sysbench.tid * per_thread
end

function thread_done()
	con:disconnect()
end

function event()
	local values = {}
	for i = 1, %d do
		uuid_idx = uuid_idx + 1
		local uuid_hex = uuids[uuid_idx]
		table.insert(values, "(UNHEX('" .. uuid_hex .. "'), UNHEX(REPEAT('41', 1024)))")
	end
	con:query("INSERT INTO " .. sysbench.opt.table_name .. " (id, data) VALUES " .. table.concat(values, ","))
end
`, batchSize, tableName, threads, batchSize)

	default:
		return fmt.Sprintf(`-- Unknown key type: %s`, keyType)
	}
}
