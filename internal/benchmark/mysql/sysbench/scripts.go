package sysbench

import (
	"fmt"
)

type ScriptType string

const (
	ScriptInsert ScriptType = "insert"
	ScriptSelect ScriptType = "select"
	ScriptUpdate ScriptType = "update"
)

// GenerateInsertScript generates a sysbench Lua script for INSERT operations.
// For UUID types, the script reads pre-generated UUIDs from /tmp/uuids.txt.
// threads is used to partition UUIDs across sysbench threads.
func GenerateInsertScript(keyType, tableName string, threads int) string {
	switch keyType {
	case "sequential":
		return fmt.Sprintf(`
-- Sysbench INSERT script for BIGINT AUTO_INCREMENT
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
}

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()
end

function thread_done()
	con:disconnect()
end

function event()
	con:query("INSERT INTO " .. sysbench.opt.table_name .. " (data) VALUES (UNHEX(REPEAT('41', 1024)))")
end
`, tableName)

	case "uuidv4", "uuidv7", "uuidv1", "ulid", "ulid_monotonic":
		// For UUID types, read pre-generated UUIDs from /tmp/uuids.txt
		// UUIDs are generated by Go (proper RFC 4122 / ULID) and copied into the container
		return fmt.Sprintf(`
-- Sysbench INSERT script for UUID/ULID types (BINARY(16))
-- UUIDs pre-generated by Go libraries for proper time-ordering
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
}

local uuids = {}
local uuid_idx = 0
local num_threads = %d

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()

	local f = io.open("/tmp/uuids.txt", "r")
	if f then
		for line in f:lines() do
			uuids[#uuids + 1] = line
		end
		f:close()
	end

	-- Each thread uses a non-overlapping partition
	local per_thread = math.floor(#uuids / num_threads)
	uuid_idx = sysbench.tid * per_thread
end

function thread_done()
	con:disconnect()
end

function event()
	uuid_idx = uuid_idx + 1
	local uuid_hex = uuids[uuid_idx]
	con:query("INSERT INTO " .. sysbench.opt.table_name .. " (id, data) VALUES (UNHEX('" .. uuid_hex .. "'), UNHEX(REPEAT('41', 1024)))")
end
`, tableName, threads)

	default:
		return fmt.Sprintf(`-- Unknown key type: %s`, keyType)
	}
}

// GenerateSelectScript generates a sysbench Lua script for SELECT operations.
// Uses a lookup table (tableName_ids) for random key selection via indexed subquery.
func GenerateSelectScript(keyType, tableName string) string {
	lookupTable := tableName + "_ids"
	return fmt.Sprintf(`
-- Sysbench SELECT script using lookup table for random key selection
sysbench.cmdline.options = {
	table_name = {"Table name", "%s"},
	num_records = {"Number of records", 0},
}

function thread_init()
	drv = sysbench.sql.driver()
	con = drv:connect()
end

function thread_done()
	con:disconnect()
end

function event()
	local rn = sysbench.rand.uniform(1, sysbench.opt.num_records)
	con:query("SELECT * FROM %s WHERE id = (SELECT id FROM %s WHERE rn = " .. rn .. ")")
end
`, tableName, tableName, lookupTable)
}

